// Seeded random numbers (mulberry32) so the city layout is stable per seed,
// plus a plain shuffle helper used by traffic and pedestrian spawns.
export function makeRng(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function pick(rng, arr) { return arr[Math.floor(rng() * arr.length)]; }

export function range(rng, lo, hi) { return lo + rng() * (hi - lo); }

export function rangeInt(rng, lo, hi) { return lo + Math.floor(rng() * (hi - lo + 1)); }

// A tiny deterministic hash of a string, for per-block variation that does not
// need the shared rng stream (buildings keep their windows between sessions).
export function hashStr(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}
export function shuffle(rng, arr) {
  const out = arr.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const tmp = out[i]; out[i] = out[j]; out[j] = tmp;
  }
  return out;
}
